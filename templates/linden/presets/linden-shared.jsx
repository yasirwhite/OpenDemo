function catmull(rows, f) {
	const n = rows.length;
	let i = 0;
	while (i < n - 2 && rows[i + 1][0] < f) i++;
	const a = rows[Math.max(0, i - 1)];
	const b = rows[i];
	const c = rows[i + 1];
	const d = rows[Math.min(n - 1, i + 2)];
	const t = clamp01((f - b[0]) / (c[0] - b[0]));
	const out = [];
	for (let k = 1; k < b.length; k++) {
		const p0 = a[k];
		const p1 = b[k];
		const p2 = c[k];
		const p3 = d[k];
		out.push(
			0.5 *
				(2 * p1 +
					(-p0 + p2) * t +
					(2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t +
					(-p0 + 3 * p1 - 3 * p2 + p3) * t * t * t),
		);
	}
	return out;
}

/** Homography (row-major 3x3) wall px -> stage px from one CAM sample. */
function dec(v) {
	const [px, py, ls, th, u00, u01, u10, g0k, g1k] = v;
	const g0 = g0k / 1000;
	const g1 = g1k / 1000;
	const u11 = (1 + u01 * u10) / u00;
	const s = Math.exp(ls);
	const c = Math.cos(th);
	const n = Math.sin(th);
	const j00 = s * (c * u00 - n * u10);
	const j01 = s * (c * u01 - n * u11);
	const j10 = s * (n * u00 + c * u10);
	const j11 = s * (n * u01 + c * u11);
	const a00 = j00 + px * g0;
	const a01 = j01 + px * g1;
	const a10 = j10 + py * g0;
	const a11 = j11 + py * g1;
	const [cx, cy] = HERO_C;
	// H = Hp * T(-c)
	return [
		[a00, a01, px - a00 * cx - a01 * cy],
		[a10, a11, py - a10 * cx - a11 * cy],
		[g0, g1, 1 - g0 * cx - g1 * cy],
	];
}

/** Camera homography at reference frame f (f114 onward). */
export const camAt = (f) => dec(catmull(CAM, f));

/** Similarity about the hero centre: screen = at + k * (P - HERO_C). */
export function simAt(at, k) {
	const [cx, cy] = HERO_C;
	return [
		[k, 0, at[0] - k * cx],
		[0, k, at[1] - k * cy],
		[0, 0, 1],
	];
}

export function apply(H, x, y) {
	const w = H[2][0] * x + H[2][1] * y + H[2][2];
	return [(H[0][0] * x + H[0][1] * y + H[0][2]) / w, (H[1][0] * x + H[1][1] * y + H[1][2]) / w];
}

/** CSS matrix3d placing a w x h box (origin 0 0) whose top-left is wall (x, y). */
export function cardMatrix(H, x, y) {
	const a = H[0][0];
	const b = H[0][1];
	const c = H[0][0] * x + H[0][1] * y + H[0][2];
	const d = H[1][0];
	const e = H[1][1];
	const f = H[1][0] * x + H[1][1] * y + H[1][2];
	const g = H[2][0];
	const h = H[2][1];
	const i = H[2][0] * x + H[2][1] * y + H[2][2];
	const r = (v) => (Math.abs(v) < 1e-12 ? 0 : Number(v.toPrecision(9)));
	return `matrix3d(${r(a)},${r(d)},0,${r(g)},${r(b)},${r(e)},0,${r(h)},0,0,1,0,${r(c)},${r(f)},0,${r(i)})`;
}

