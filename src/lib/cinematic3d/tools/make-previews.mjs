// Regenerate the preview strip for every shot preset.
//
//   node src/lib/cinematic3d/tools/make-previews.mjs [preset ...]
//
// Each preset gets one JPEG in presets/previews/ showing three moments — start,
// middle, end — side by side. A strip rather than a video on purpose: it shows
// where the shot travels, costs ~60 KB, and does not grow the repo every time
// the library grows. Run this after adding or retuning a preset.
import { chromium } from "playwright";
import { serve } from "../serve.mjs";
import { PRESETS, PRESET_NOTES, PRESET_NATIVE_MS } from "../presets/index.js";
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const HERE = import.meta.dirname;
const OUT = join(HERE, "..", "presets", "previews");
mkdirSync(OUT, { recursive: true });

const only = process.argv.slice(2);
const names = Object.keys(PRESETS).filter((n) => !only.length || only.includes(n));
const W = 960, H = 540;                 // per-panel; the strip is 3 x this
const AT = [0.06, 0.5, 0.94];           // where in the shot to sample

const { server, port } = await serve(8781);
const browser = await chromium.launch({
  headless: true,
  args: ["--use-angle=d3d11", "--enable-gpu", "--ignore-gpu-blocklist", "--disable-dev-shm-usage"],
});

// Preview shots use the placeholder UI, so the strip shows the CAMERA WORK rather
// than whatever recording happened to be lying around — and each runs at its OWN
// native duration, so the strip is the shot as tuned, not a retimed version of it.
const configFor = (preset) => ({
  width: W, height: H,
  scenes: [{ preset, duration: (PRESET_NATIVE_MS[preset] ?? 6000) / 1000 }],
});

const strip = await browser.newPage({ viewport: { width: 200, height: 200 } });
const rows = [];

for (const name of names) {
  const cfgUrl = `data:application/json,${encodeURIComponent(JSON.stringify(configFor(name)))}`;
  const page = await browser.newPage({ viewport: { width: W / 2, height: H / 2 } });
  page.on("pageerror", (e) => console.log(`PAGEERROR [${name}]:`, e.message));
  await page.goto(
    `http://127.0.0.1:${port}/src/lib/cinematic3d/scene.html?w=${W}&h=${H}&config=${encodeURIComponent(cfgUrl)}`,
    { waitUntil: "load" }
  );
  await page.waitForFunction("window.__ready === true", { timeout: 120000 });
  const dur = await page.evaluate("window.DURATION");

  const shots = [];
  for (const u of AT) {
    shots.push(await page.evaluate(async (t) => {
      if (window.prepareFrame) await window.prepareFrame(t);
      window.renderAtTime(t);
      return document.querySelector("canvas").toDataURL("image/jpeg", 0.92);
    }, u * dur));
  }
  await page.close();

  const jpeg = await strip.evaluate(async ([imgs, w, h]) => {
    const c = document.createElement("canvas");
    c.width = w * imgs.length + 8 * (imgs.length - 1);
    c.height = h;
    const g = c.getContext("2d");
    g.fillStyle = "#000"; g.fillRect(0, 0, c.width, c.height);
    for (let i = 0; i < imgs.length; i++) {
      const im = new Image();
      await new Promise((r) => { im.onload = r; im.src = imgs[i]; });
      g.drawImage(im, i * (w + 8), 0, w, h);
    }
    return c.toDataURL("image/jpeg", 0.82);
  }, [shots, W, H]);

  const file = join(OUT, `${name}.jpg`);
  const bytes = Buffer.from(jpeg.split(",")[1], "base64");
  writeFileSync(file, bytes);
  rows.push({ name, kb: Math.round(bytes.length / 1024), secs: dur });
  console.log(`${name.padEnd(22)} ${String(Math.round(bytes.length / 1024)).padStart(4)} KB`);
}

writeFileSync(
  join(OUT, "README.md"),
  `# Preset previews\n\n` +
    `Auto-generated by \`tools/make-previews.mjs\`. Each strip is three moments from the\n` +
    `shot — **start · middle · end** — rendered with the placeholder UI so what you are\n` +
    `looking at is the camera work, not the content.\n\n` +
    `Regenerate after adding or retuning a preset:\n\n` +
    "```bash\nnode src/lib/cinematic3d/tools/make-previews.mjs            # all\nnode src/lib/cinematic3d/tools/make-previews.mjs raw-2d     # one\n```\n\n" +
    rows
      .map(
        (r) =>
          `## \`${r.name}\`\n\n${PRESET_NOTES[r.name]}\n\n` +
          `Tuned at **${r.secs}s** — the duration at which it reproduces the reference shot.\n` +
          `Other durations rescale its sub-cuts proportionally.\n\n` +
          `![${r.name}](${r.name}.jpg)\n`
      )
      .join("\n"),
  "utf8"
);
console.log(`\nwrote ${rows.length} strips + README.md -> ${OUT}`);

await browser.close();
server.close();
